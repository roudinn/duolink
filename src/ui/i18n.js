function notice(message) {
  if (language.value !== "en" || !message) return message;
  if (Object.hasOwn(EN, message)) return EN[message];
  const separator = ": ";
  const causeAt = message.indexOf(separator);
  const context = causeAt === -1 ? message : message.slice(0, causeAt);
  const cause = causeAt === -1 ? "" : message.slice(causeAt + separator.length);
  let translated = tr(context);
  for (const [pattern, translate] of nativePatterns) {
    if (pattern.test(context)) {
      translated = context.replace(pattern, translate);
      break;
    }
  }
  const fallback = " Отправьте другу код сессии.";
  if (message.endsWith(fallback)) {
    return `${notice(message.slice(0, -fallback.length))} ${tr(fallback.trim())}`;
  }
  return cause ? `${translated}${separator}${notice(cause)}` : translated;
}

function factValue(label, value) {
  if (language.value !== "en") return value;
  if (label === "Гость") return value.replace(/^Гость(?= · )/u, "Guest");
  return value.split(" · ").map((part) => tr(part)
    .replace(/(?<=\d) мс$/u, " ms")
    .replace(/(?<=\d) Гц$/u, " Hz")
    .replace(/(?<=\d) Мбит\/с$/u, " Mbps")
    .replace(/^быстрее /u, "over ")
    .replace(/^коррекция /u, "FEC ")
    .replace(/^по каналу$/u, "bandwidth limit")).join(" · ");
}

// Capture only the original document strings, before the first IPC state.
const staticStrings = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  const value = node.nodeValue;
  const key = value.trim();
  if (Object.hasOwn(EN, key)) staticStrings.push(() => { node.nodeValue = value.replace(key, tr(key)); });
}
for (const element of document.querySelectorAll("[aria-label], [title], [placeholder]")) {
  for (const attribute of ["aria-label", "title", "placeholder"]) {
    const key = element.getAttribute(attribute);
    if (Object.hasOwn(EN, key)) staticStrings.push(() => element.setAttribute(attribute, tr(key)));
  }
}

function applyLanguage() {
  document.documentElement.lang = language.value;
  for (const translate of staticStrings) translate();
}

try {
  if (localStorage.getItem(languageKey) === "en") language.value = "en";
} catch { /* storage unavailable */ }
applyLanguage();
